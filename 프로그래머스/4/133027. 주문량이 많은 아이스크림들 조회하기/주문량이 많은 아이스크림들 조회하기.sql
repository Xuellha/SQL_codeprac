WITH HALF_TABLE AS (SELECT FLAVOR, SUM(TOTAL_ORDER) AS TOTAL_ORDER
    FROM FIRST_HALF 
    GROUP BY FLAVOR),
    
JULY_TABLE AS (
    SELECT FLAVOR, SUM(TOTAL_ORDER) AS TOTAL_ORDER
    FROM JULY
    GROUP BY FLAVOR)
 
SELECT FLAVOR
FROM (SELECT HT.FLAVOR, (HT.TOTAL_ORDER + JT.TOTAL_ORDER) AS TOTAL_ORDER
    FROM HALF_TABLE HT
    JOIN JULY_TABLE JT
        ON HT.FLAVOR = JT.FLAVOR
    ORDER BY TOTAL_ORDER DESC
    LIMIT 3) F

